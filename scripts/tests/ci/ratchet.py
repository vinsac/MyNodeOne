#!/usr/bin/env python3
"""Lint ratchets: existing findings are accepted, new ones fail.

    ratchet.py shellcheck check     # compare with shellcheck-baseline.txt
    ratchet.py shellcheck update    # rewrite the baseline from the current tree
    ratchet.py ruff check
    ratchet.py ruff update

A baseline counts findings per (file, severity, rule), not per line, so moving code
doesn't trip it, and a fix in one file can't pay for new debt in another. Run update
after paying debt down so the lower count becomes the limit. Check says when it can.

The counts depend on the tool's version, so the baseline records it and check warns on
a mismatch. CI installs the recorded versions from requirements-ci.txt.

SHELLCHECK and RUFF override the commands to run.
"""
import collections
import json
import os
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[2]
GATEWAY = "scripts/apps/llmapi/gateway"
# xargs-style batching. shellcheck takes many paths, but not unlimited ones.
BATCH = 40


def tracked(pattern):
    out = subprocess.run([str(HERE / "tracked-files.sh"), pattern], check=True, capture_output=True, text=True)
    return out.stdout.split("\n")[:-1]


def command_output(command, ok_codes):
    done = subprocess.run(command, cwd=REPO, capture_output=True, text=True)
    if done.returncode not in ok_codes:
        sys.exit(f"{command[0]} failed with exit {done.returncode}:\n{done.stderr}")
    return done.stdout


def shellcheck_version(tool):
    for line in command_output([tool, "--version"], {0}).splitlines():
        if line.startswith("version:"):
            return "shellcheck " + line.split()[1]
    sys.exit("could not read shellcheck's version")


def shellcheck_findings(tool):
    counts = collections.Counter()
    files = tracked("*.sh")
    for start in range(0, len(files), BATCH):
        # Exit 1 means it found something, which is what we're here to count.
        output = command_output([tool, "-S", "warning", "-f", "json", *files[start:start + BATCH]], {0, 1})
        for finding in json.loads(output or "[]"):
            counts[(finding["file"], finding["level"], f"SC{finding['code']}")] += 1
    return counts


def ruff_version(tool):
    return command_output([tool, "--version"], {0}).strip()


def ruff_findings(tool):
    output = command_output([tool, "check", "--no-cache", "--output-format=json", GATEWAY], {0, 1})
    counts = collections.Counter()
    for finding in json.loads(output or "[]"):
        path = pathlib.Path(finding["filename"]).resolve().relative_to(REPO).as_posix()
        counts[(path, "error", finding["code"] or "syntax")] += 1
    return counts


LINTERS = {
    "shellcheck": (os.environ.get("SHELLCHECK", "shellcheck"), shellcheck_version, shellcheck_findings),
    "ruff": (os.environ.get("RUFF", "ruff"), ruff_version, ruff_findings),
}


def read_baseline(path):
    version = None
    counts = collections.Counter()
    for line in path.read_text().splitlines():
        if line.startswith("# version: "):
            version = line[len("# version: "):]
        elif line and not line.startswith("#"):
            file, level, code, count = line.split("\t")
            counts[(file, level, code)] = int(count)
    return version, counts


def write_baseline(path, linter, version, counts):
    lines = [
        f"# Accepted {linter} findings. New ones fail CI; do not add to this by hand.",
        f"# Regenerate after paying debt down: scripts/tests/ci/ratchet.py {linter} update",
        f"# version: {version}",
        "# file\tseverity\trule\tcount",
    ]
    lines += ["\t".join((*key, str(counts[key]))) for key in sorted(counts)]
    path.write_text("\n".join(lines) + "\n")


def check(linter, path, version, counts):
    baseline_version, baseline = read_baseline(path)
    if baseline_version != version:
        print(f"WARNING: the baseline was generated by {baseline_version} but this is {version}, "
              "so differences below may only be the tool's.")
    grown = sorted(key for key in counts if counts[key] > baseline[key])
    shrunk = sorted(key for key in baseline if counts[key] < baseline[key])
    total, accepted = sum(counts.values()), sum(baseline.values())
    print(f"{linter}: {total} findings, {accepted} accepted in {path.name}")

    known_errors = sorted(key for key in counts if key[1] == "error" and linter == "shellcheck")
    for file, _, code in known_errors:
        if counts[(file, "error", code)] <= baseline[(file, "error", code)]:
            print(f"KNOWN ERROR, accepted for now: {file} {code}")

    for key in shrunk:
        print(f"improved: {key[0]} {key[2]}: {baseline[key]} -> {counts[key]}")
    if shrunk:
        print(f"Lock the improvement in: scripts/tests/ci/ratchet.py {linter} update")
    for key in grown:
        print(f"NEW DEBT: {key[0]} {key[1]} {key[2]}: {baseline[key]} accepted, {counts[key]} found")
    if grown:
        print(f"{linter}: {len(grown)} file and rule pairs got worse. Fix them; the accepted list is for old debt.")
        return 1
    return 0


def main():
    if len(sys.argv) != 3 or sys.argv[1] not in LINTERS or sys.argv[2] not in ("check", "update"):
        sys.exit(__doc__)
    linter, action = sys.argv[1:]
    tool, get_version, get_findings = LINTERS[linter]
    path = HERE / f"{linter}-baseline.txt"
    version = get_version(tool)
    counts = get_findings(tool)
    if action == "update":
        write_baseline(path, linter, version, counts)
        print(f"{path.relative_to(REPO)}: {sum(counts.values())} findings accepted")
        return 0
    return check(linter, path, version, counts)


if __name__ == "__main__":
    sys.exit(main())
